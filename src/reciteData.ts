/** 篇名 → 默写题列表 */
export const QUIZ_MAP: Record<string, { p: string; a: string }[]> = (() => {
  const map: Record<string, { p: string; a: string }[]> = {};
  for (const raw of QUIZ_SRC.split('\n')) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const [title, p, a] = line.split('|').map(s => s.trim());
    if (!title || !p || !a) continue;
    (map[title] ||= []).push({ p, a });
  }
  return map;
})();

export const QUIZ_COUNT = Object.values(QUIZ_MAP).reduce((s, v) => s + v.length, 0);
/** 题库覆盖的篇目数 */
export const QUIZ_POEM_COUNT = Object.keys(QUIZ_MAP).length;

/** 每行格式：篇名 | 作者/出处 | 文体 | 要求(both=背诵+默写, recite=仅背诵) */
function parse(src: string): PresetPoem[] {
  const out: PresetPoem[] = [];
  for (const raw of src.split('\n')) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const [title, author, type, req] = line.split('|').map(s => s.trim());
    if (!title) continue;
    out.push({
      title,
      author: author || '',
      type: (type as PoemType) || '诗',
      req: (req as PoemReq) || 'both',
      kebiao: KEBIAO_SET.has(title) || undefined,
      quiz: QUIZ_MAP[title],
    });
  }
  return out;
}

